int vqeaf_text_next_grapheme(const char *s,uint32_t *cp,int *composed,int *len,int *marks){
 if(!s||!cp||!composed||!len||!marks)return 0;
 *composed=0;*marks=0;
 int n=vqeaf_utf8_next(s,cp);
 if(!n)return 0;
 *len=n;
 const char *p=s+n;
 uint32_t m;
 while((n=vqeaf_utf8_next(p,&m))&&vqeaf_text_is_combining(m)){
  uint32_t composed_cp=vqeaf_text_compose(*cp,m);
  if(composed_cp){*cp=composed_cp;*composed=1;} /* chain: e+^ -> ê, +dot below -> ệ */
  (*marks)++;*len+=n;p+=n;
 }
 return 1;
}
