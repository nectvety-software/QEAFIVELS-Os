int vqeaf_utf8_next(const char *s,uint32_t *cp){
 if(!s||!cp)return 0;
 const unsigned char *p=(const unsigned char*)s;
 uint32_t c=p[0];
 if(!c)return 0;
 if(c<0x80){*cp=c;return 1;}
 unsigned n;uint32_t v;
 if((c&0xE0)==0xC0){n=2;v=c&0x1Fu;}
 else if((c&0xF0)==0xE0){n=3;v=c&0x0Fu;}
 else if((c&0xF8)==0xF0){n=4;v=c&0x07u;}
 else return 0;
 for(unsigned i=1;i<n;i++){
  if((p[i]&0xC0)!=0x80)return 0;
  v=(v<<6)|(p[i]&0x3Fu);
 }
 if(n==2&&v<0x80)return 0;            /* overlong */
 if(n==3&&v<0x800)return 0;
 if(n==4&&v<0x10000)return 0;
 if(v>0x10FFFF||(v>=0xD800&&v<=0xDFFF))return 0; /* surrogate or out of range */
 *cp=v;return (int)n;
}
int vqeaf_text_is_combining(uint32_t cp){
 return (cp>=0x0300u&&cp<=0x036Fu)||(cp>=0x1AB0u&&cp<=0x1AFFu)||(cp>=0x1DC0u&&cp<=0x1DFFu)||(cp>=0x20D0u&&cp<=0x20FFu);
}
