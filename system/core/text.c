uint32_t vqeaf_text_glyph_fallback(uint32_t cp){
 if(cp<0x80u)return cp;                     /* font v0.3 covers ASCII */
 if(cp>=0x1EA0u&&cp<=0x1EFFu)return cp;     /* and Vietnamese Latin Extended Additional */
 if(cp>=0x00C0u&&cp<=0x00FFu)return cp;     /* and Latin-1 letters used in Vietnamese */
 uint32_t base=vqeaf_text_base_letter(cp);
 if(base)return base;
 return VQEAF_TEXT_REPLACEMENT;
}
uint32_t vqeaf_text_advance(uint32_t cp){
 if(vqeaf_text_is_combining(cp))return 0;
 uint32_t g=vqeaf_text_glyph_fallback(cp);
 if(g==VQEAF_TEXT_REPLACEMENT)return 700u;
 if(g=='i'||g=='l'||g=='I'||g=='j'||g=='!'||g=='.'||g==','||g=='\''||g=='|')return 280u;
 if(g=='m'||g=='M'||g=='W'||g=='w')return 940u;
 if(g==' ')return 320u;
 /* wide scripts only (Hangul/CJK/fullwidth); Latin Extended stays narrow */
 if((g>=0x1100u&&g<=0x11FFu)||(g>=0x2E80u&&g<=0x9FFFu)||(g>=0xAC00u&&g<=0xD7AFu)||(g>=0xF900u&&g<=0xFAFFu)||(g>=0xFF00u&&g<=0xFF60u)||(g>=0x1F300u))return 1000u;
 return 600u;
}
int vqeaf_text_measure(const char *utf8,uint32_t *width,uint32_t *graphemes){
 if(!utf8||!width||!graphemes)return -1;
 uint32_t w=0,g=0;const char *p=utf8;
 for(;;){
  uint32_t cp;int composed=0,len=0,marks=0;
  if(!vqeaf_text_next_grapheme(p,&cp,&composed,&len,&marks))break;
  w+=vqeaf_text_advance(cp);
  g++;
  p+=len;
  if(!*p)break;
 }
 if(*p)return -2; /* malformed UTF-8 */
 *width=w;*graphemes=g;
 return 0;
}
