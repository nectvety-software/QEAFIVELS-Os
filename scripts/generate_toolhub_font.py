import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "platform/violet/ui/fonts/vqeaf_font_20.c"
OUT = ROOT / "examples/qeaf-toolhub/src/font_data"


def array(name, text):
    match = re.search(r"\b" + re.escape(name) + r"\[\]\s*=\s*\{(.*?)\};", text, re.S)
    if not match:
        raise ValueError(f"missing array {name}")
    return [int(value, 0) for value in re.findall(r"\b(?:0x[0-9A-Fa-f]+|\d+)\b", match.group(1))]


def emit_array(lines, declaration, values, per_line):
    lines.append(declaration + " = {")
    for start in range(0, len(values), per_line):
        chunk = values[start:start + per_line]
        if declaration.startswith("const uint8_t"):
            rendered = ", ".join(str(value) for value in chunk)
        else:
            rendered = ", ".join(f"0x{value:X}" if "codepoints" in declaration else str(value)
                                 for value in chunk)
        lines.append("    " + rendered + ",")
    lines.append("};")
    lines.append("")


def main():
    text = SOURCE.read_text(encoding="utf-8")
    bitmap = array("glyph_bitmap", text)
    offsets = array("unicode_list_0", text)
    descriptors = re.findall(
        r"\{\.bitmap_index\s*=\s*(\d+),\s*\.adv_w\s*=\s*(\d+),\s*"
        r"\.box_w\s*=\s*(\d+),\s*\.box_h\s*=\s*(\d+),\s*"
        r"\.ofs_x\s*=\s*(-?\d+),\s*\.ofs_y\s*=\s*(-?\d+)\}",
        text,
    )
    range_match = re.search(r"\.range_start\s*=\s*(\d+)", text)
    if not range_match or len(descriptors) != len(offsets) + 1:
        raise ValueError("unexpected LVGL font layout")
    if len(bitmap) > 0xFFFFFFFF or len(offsets) > 0xFFFF:
        raise ValueError("font exceeds scalar extraction limits")
    range_start = int(range_match.group(1))
    codepoints = [range_start + value for value in offsets]
    glyphs = []
    for descriptor in descriptors[1:]:
        values = [int(value) for value in descriptor]
        if not (0 <= values[1] <= 0xFFFF and 0 <= values[2] <= 0xFF
                and 0 <= values[3] <= 0xFF and -128 <= values[4] <= 127
                and -128 <= values[5] <= 127):
            raise ValueError("glyph metric does not fit app-local record")
        glyphs.append(values)

    OUT.mkdir(parents=True, exist_ok=True)
    header = [
        "/* Generated by scripts/generate_toolhub_font.py; do not edit by hand. */",
        "#ifndef TOOLHUB_FONT_DATA_H",
        "#define TOOLHUB_FONT_DATA_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint32_t bitmap_offset;",
        "    uint16_t advance;",
        "    uint8_t width;",
        "    uint8_t height;",
        "    int8_t ofs_x;",
        "    int8_t ofs_y;",
        "} toolhub_font_glyph_t;",
        "",
        f"#define TOOLHUB_FONT_COUNT {len(codepoints)}u",
        "#define TOOLHUB_FONT_HIDDEN __attribute__((visibility(\"hidden\")))",
        "extern TOOLHUB_FONT_HIDDEN const uint16_t toolhub_font_codepoints[TOOLHUB_FONT_COUNT];",
        "extern TOOLHUB_FONT_HIDDEN const toolhub_font_glyph_t toolhub_font_glyphs[TOOLHUB_FONT_COUNT];",
        "extern TOOLHUB_FONT_HIDDEN const uint8_t toolhub_font_bitmap[];",
        "extern TOOLHUB_FONT_HIDDEN const uint32_t toolhub_font_bitmap_size;",
        "",
        "#endif",
        "",
    ]
    (OUT / "font_data.h").write_text("\n".join(header), encoding="ascii")

    source = [
        "/* Generated by scripts/generate_toolhub_font.py; do not edit by hand. */",
        '#include "font_data.h"',
        "",
    ]
    emit_array(source, "const uint16_t toolhub_font_codepoints[TOOLHUB_FONT_COUNT]",
               codepoints, 12)
    source.append("const toolhub_font_glyph_t toolhub_font_glyphs[TOOLHUB_FONT_COUNT] = {")
    for glyph in glyphs:
        source.append("    {%du, %du, %du, %du, %d, %d}," % tuple(glyph))
    source.extend(["};", ""])
    emit_array(source, "const uint8_t toolhub_font_bitmap[]", bitmap, 20)
    source.append(f"const uint32_t toolhub_font_bitmap_size = {len(bitmap)}u;")
    source.append("")
    (OUT / "font_data.c").write_text("\n".join(source), encoding="ascii")
    print(f"generated {len(codepoints)} glyphs and {len(bitmap)} bitmap bytes")


if __name__ == "__main__":
    main()
