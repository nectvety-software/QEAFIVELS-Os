"""Wrap raw .text into a minimal static ELF64 executable and emit a C header.

The mingw64 toolchain cannot link ELF images, so the ring-3 user program is
compiled to a COFF object, its .text extracted to raw bytes, and wrapped here.
Entry point = the first byte of .text (the program must keep _start first).
"""
import shutil, subprocess, sys, os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OBJ = ROOT / "build" / "user_hello.o"
BIN = ROOT / "build" / "user_hello.bin"
OUT = ROOT / "user" / "hello_elf.h"
BASE = 0x10000000000  # VQEAF_USER_REGION_BASE

def main():
    cc = os.environ.get("VQEAF_CC", "x86_64-w64-mingw32-gcc")
    objcopy = os.environ.get("VQEAF_OBJCOPY")
    if not objcopy:
        for cand in ("x86_64-w64-mingw32-objcopy", r"C:/msys64/mingw64/bin/objcopy.exe"):
            if shutil.which(cand) or Path(cand).is_file():
                objcopy = cand
                break
    if not objcopy:
        raise SystemExit("no objcopy found; set VQEAF_OBJCOPY")
    subprocess.run([cc, "-c", str(ROOT/"user"/"hello.c"), "-O1", "-ffreestanding",
                    "-fno-stack-protector", "-fno-stack-check", "-fno-builtin",
                    "-Wall", "-Wextra", "-o", str(OBJ)], check=True)
    subprocess.run([objcopy, "-O", "binary", "--only-section=.text", str(OBJ), str(BIN)], check=True)
    code = BIN.read_bytes()
    if not code:
        raise SystemExit("empty .text")
    ehdr = bytearray(64)
    ehdr[0:4] = b"\x7fELF"
    ehdr[4] = 2          # ELFCLASS64
    ehdr[5] = 1          # little endian
    ehdr[6] = 1          # version
    ehdr[16:18] = (2).to_bytes(2, "little")    # ET_EXEC
    ehdr[18:20] = (0x3E).to_bytes(2, "little") # EM_X86_64
    ehdr[20:24] = (1).to_bytes(4, "little")
    ehdr[24:32] = BASE.to_bytes(8, "little")   # entry
    ehdr[32:40] = (64).to_bytes(8, "little")   # phoff
    ehdr[52:54] = (64).to_bytes(2, "little")
    ehdr[54:56] = (56).to_bytes(2, "little")   # phentsize
    ehdr[56:58] = (1).to_bytes(2, "little")    # phnum
    phdr = bytearray(56)
    phdr[0:4] = (1).to_bytes(4, "little")      # PT_LOAD
    phdr[4:8] = (7).to_bytes(4, "little")      # RWX
    phdr[8:16] = (120).to_bytes(8, "little")  # file offset of code (ehdr 64 + phdr 56)
    phdr[16:24] = BASE.to_bytes(8, "little")
    phdr[24:32] = BASE.to_bytes(8, "little")
    phdr[32:40] = len(code).to_bytes(8, "little")
    phdr[40:48] = len(code).to_bytes(8, "little")
    phdr[48:56] = (0x1000).to_bytes(8, "little")
    image = bytes(ehdr) + bytes(phdr) + code
    lines = [f"/* Generated by scripts/gen_user_elf.py; do not edit. {len(code)} bytes of code. */",
             "#ifndef VQEAF_USER_HELLO_ELF_H", "#define VQEAF_USER_HELLO_ELF_H",
             f"#define VQEAF_USER_HELLO_ENTRY {BASE:#x}ull",
             f"#define VQEAF_USER_HELLO_SIZE {len(image)}u",
             "static const unsigned char vqeaf_user_hello_elf[] = {"]
    for i in range(0, len(image), 16):
        lines.append(" " + ",".join(f"0x{b:02x}" for b in image[i:i+16]) + ",")
    lines.append("};")
    lines.append("#endif")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"user ELF: {len(image)} bytes image, {len(code)} bytes code -> {OUT.name}")

if __name__ == "__main__":
    main()
