#!/usr/bin/env python3
"""Build EL0 AArch64 user programs into real static ELFs and embed them.

zig links each user/<name>.S at 0x10000000000 (hello_aarch64.ld) into an
ET_EXEC EM_AARCH64 image. The bytes are emitted as an 8-byte-aligned C array in
user/<name>_elf.h, which the kernel loads via the portable vqeaf_elf_load.
Unlike the x86 path (gen_user_elf.py, COFF .text extraction), zig produces ELF
directly, so no objcopy wrapping is needed.

Programs: hello_aarch64 (EL0 hello), ipc_send_aarch64 / ipc_recv_aarch64
(Binder-like kernel IPC between two isolated EL0 tasks).
"""
import os
import struct
import subprocess
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "build" / "kernel-aarch64"
BASE = 0x10000000000
LIMIT = 0x14000000000
PROGRAMS = ["hello_aarch64", "ipc_send_aarch64", "ipc_recv_aarch64",
            "surface_client_aarch64", "launcher_aarch64"]


def find_zig():
    env = os.environ.get("ZIG")
    if env and Path(env).is_file():
        return env
    base = os.environ.get("QEAFDROPOS") or "D:\\QeafivelsOfficial\\QeafdropOs"
    candidate = Path(base) / "out" / "toolchain" / "zig-windows-x86_64-0.13.0" / "zig.exe"
    if candidate.is_file():
        return str(candidate)
    raise SystemExit("zig toolchain not found; set ZIG=/path/to/zig")


def build_one(zig, name):
    elf = OUT / ("user_" + name + ".elf")
    is_c = name == "launcher_aarch64"
    src = ROOT / "user" / (name + (".c" if is_c else ".S"))
    ld = ROOT / "user" / (name + ".ld" if is_c else "hello_aarch64.ld")
    cmd = [zig, "cc", "-target", "aarch64-linux-musl", "-ffreestanding",
           "-fno-pie", "-no-pie", "-nostdlib", "-mstrict-align",
           "-fno-builtin", "-fno-stack-protector", "-O2",
           "-I", str(ROOT / "kernel" / "include"),
           "-Wl,-T," + ld.as_posix(),
           "-Wl,--build-id=none", "-Wl,-e,_start", "-Wl,-z,max-page-size=4096",
           "-o", str(elf), str(src)]
    proc = subprocess.run(cmd, capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=180)
    if proc.returncode != 0:
        raise SystemExit("user ELF aarch64 link FAILED %s:\n%s"
                         % (name, proc.stderr or proc.stdout))
    image = elf.read_bytes()
    if image[:4] != b"\x7fELF" or image[4] != 2 or image[5] != 1:
        raise SystemExit("user ELF %s: not ELF64 little-endian" % name)
    e_type, e_machine = struct.unpack_from("<HH", image, 16)
    e_entry = struct.unpack_from("<Q", image, 24)[0]
    if e_type != 2:
        raise SystemExit("user ELF %s: not ET_EXEC (e_type=%d)" % (name, e_type))
    if e_machine != 0xB7:
        raise SystemExit("user ELF %s: not EM_AARCH64 (0x%x)" % (name, e_machine))
    if not (BASE <= e_entry < LIMIT):
        raise SystemExit("user ELF %s: entry out of user region (0x%x)" % (name, e_entry))
    upper = name.upper()
    hdr = ROOT / "user" / (name + "_elf.h")
    lines = ["/* Generated by scripts/gen_user_elf_aarch64.py; do not edit. %d bytes. */" % len(image),
             "#ifndef VQEAF_USER_%s_ELF_H" % upper,
             "#define VQEAF_USER_%s_ELF_H" % upper,
             "#define VQEAF_USER_%s_ENTRY 0x%xull" % (upper, e_entry),
             "#define VQEAF_USER_%s_SIZE %du" % (upper, len(image)),
             "__attribute__((aligned(8))) static const unsigned char vqeaf_user_%s_elf[] = {" % name]
    for i in range(0, len(image), 16):
        lines.append(" " + ",".join("0x%02x" % b for b in image[i:i+16]) + ",")
    lines.append("};")
    lines.append("#endif")
    hdr.write_text("\n".join(lines) + "\n")
    print("gen_user_elf_aarch64: %s %d byte ELF, entry=0x%x -> %s"
          % (name, len(image), e_entry, hdr.name))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    zig = find_zig()
    for name in PROGRAMS:
        build_one(zig, name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())